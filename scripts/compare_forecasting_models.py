import os
import pandas as pd
import matplotlib.pyplot as plt

REPORT_DIR = "reports"
os.makedirs(REPORT_DIR, exist_ok=True)


def load_result(path):
    if not os.path.exists(path):
        print(f"WARNING - Not found: {path}")
        return pd.DataFrame()
    result = pd.read_csv(path)
    print(f"Loaded: {path}")
    return result


# Load trained-model results.
result_files = [
    "reports/ml_forecasting_results.csv",
    "reports/prophet_forecasting_results.csv",
    "reports/lstm_forecasting_results.csv",
    "reports/gru_forecasting_results.csv",
]
model_frames = [load_result(path) for path in result_files]
model_frames = [frame for frame in model_frames if not frame.empty]

if not model_frames:
    raise FileNotFoundError(
        "No model result CSVs were found in reports/. "
        "Run the forecasting scripts before comparing models."
    )

# Load baseline results generated by baseline_forecasting.py.
baseline_frames = []
baseline_sources = [
    (
        "data/processed/forecasting/baseline_session_results.csv",
        "target_sessions_next_hour",
    ),
    (
        "data/processed/forecasting/baseline_energy_results.csv",
        "target_energy_next_hour",
    ),
]

for path, target_name in baseline_sources:
    frame = load_result(path)
    if frame.empty:
        continue

    frame = frame.copy()
    frame["Target"] = target_name
    frame["WAPE_percent"] = pd.NA
    frame["sMAPE_percent"] = pd.NA
    baseline_frames.append(frame)

if not baseline_frames:
    raise FileNotFoundError(
        "Baseline result CSVs were not found. "
        "Run: python scripts/baseline_forecasting.py"
    )

comparison = pd.concat(
    model_frames + baseline_frames,
    ignore_index=True,
    sort=False,
)

# Normalize target labels used by the different model scripts.
comparison["Target"] = comparison["Target"].astype(str).replace({
    "sessions": "target_sessions_next_hour",
    "energy": "target_energy_next_hour",
})

# Normalize baseline model names for a consistent dashboard/report.
comparison["Model"] = comparison["Model"].replace({
    "Seasonal Naive - 24h": "Seasonal 24h",
    "Seasonal Naive - 168h": "Seasonal 168h",
})

model_type = {
    "Naive": "Baseline",
    "Seasonal 24h": "Baseline",
    "Seasonal 168h": "Baseline",
    "Random Forest": "Machine Learning",
    "XGBoost": "Machine Learning",
    "LightGBM": "Machine Learning",
    "Prophet": "Statistical",
    "LSTM": "Deep Learning",
    "GRU": "Deep Learning",
}
comparison["Model_Type"] = comparison["Model"].map(model_type).fillna("Other")

# Compare each model against the corrected same-target-hour previous-week baseline.
weekly_baseline = comparison[
    comparison["Model"] == "Seasonal 168h"
][["Target", "MAE"]].rename(columns={"MAE": "Baseline_MAE"})

comparison = comparison.drop(
    columns=["Baseline_MAE", "Improvement_over_168h_percent"],
    errors="ignore",
)
comparison = comparison.merge(
    weekly_baseline,
    on="Target",
    how="left",
)

comparison["Improvement_over_168h_percent"] = (
    (comparison["Baseline_MAE"] - comparison["MAE"])
    / comparison["Baseline_MAE"]
) * 100

for column in ["MAE", "RMSE", "WAPE_percent", "sMAPE_percent",
               "Baseline_MAE", "Improvement_over_168h_percent"]:
    if column in comparison.columns:
        comparison[column] = pd.to_numeric(
            comparison[column], errors="coerce"
        )

comparison["MAE"] = comparison["MAE"].round(4)
comparison["RMSE"] = comparison["RMSE"].round(4)
comparison["WAPE_percent"] = comparison["WAPE_percent"].round(4)
comparison["sMAPE_percent"] = comparison["sMAPE_percent"].round(4)
comparison["Baseline_MAE"] = comparison["Baseline_MAE"].round(4)
comparison["Improvement_over_168h_percent"] = (
    comparison["Improvement_over_168h_percent"].round(2)
)

comparison = comparison.sort_values(
    ["Target", "MAE"]
).reset_index(drop=True)

output_file = os.path.join(
    REPORT_DIR,
    "forecasting_model_comparison.csv",
)
comparison.to_csv(output_file, index=False)

print("\n" + "=" * 80)
print("EVChargeIQ - FORECASTING MODEL COMPARISON")
print("=" * 80)
print(comparison[
    [
        "Model", "Model_Type", "Target", "MAE", "RMSE",
        "WAPE_percent", "sMAPE_percent",
        "Baseline_MAE", "Improvement_over_168h_percent",
    ]
].to_string(index=False))

print("\nBEST MODEL BY MAE")
for target in comparison["Target"].dropna().unique():
    target_df = comparison[comparison["Target"] == target].dropna(subset=["MAE"])
    if target_df.empty:
        continue
    best = target_df.loc[target_df["MAE"].idxmin()]
    print(
        f"{target}: {best['Model']} | MAE={best['MAE']:.4f} | "
        f"Improvement over corrected weekly baseline="
        f"{best['Improvement_over_168h_percent']:.2f}%"
    )

# Save MAE charts for each target.
plot_configs = [
    ("target_sessions_next_hour", "sessions", "Session Forecasting"),
    ("target_energy_next_hour", "energy", "Energy Forecasting"),
]
for target_key, filename, title in plot_configs:
    subset = comparison[comparison["Target"] == target_key].copy()
    subset = subset.dropna(subset=["MAE"]).sort_values("MAE")
    if subset.empty:
        continue

    plt.figure(figsize=(12, 6))
    plt.bar(subset["Model"], subset["MAE"])
    plt.title(f"EVChargeIQ - {title} MAE Comparison")
    plt.xlabel("Model")
    plt.ylabel("MAE (lower is better)")
    plt.xticks(rotation=40, ha="right")
    plt.tight_layout()
    plot_path = os.path.join(
        REPORT_DIR,
        f"forecasting_{filename}_mae_comparison.png",
    )
    plt.savefig(plot_path, dpi=150)
    plt.close()
    print(f"Saved: {plot_path}")

print(f"\nSaved: {output_file}")
print("Forecasting comparison completed.")
